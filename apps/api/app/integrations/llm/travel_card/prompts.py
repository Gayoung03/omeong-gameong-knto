"""단계 3 — 이미지 편집 프롬프트 조립.

**LLM 을 부르지 않는다.** 문자열을 합칠 뿐이다. 그래서 이 단계는 공짜이고, 실패하지
않고, 테스트가 쉽다. 프롬프트를 고칠 때 모델 호출 없이 결과를 눈으로 확인할 수 있다.

세 조각으로 나눈다.

    공통 스타일   그림체·펜·장식 규칙 (말투마다 조금 다름)
    분류별 내용   kind 마다 무엇을 짚을지
    가드          하지 말 것. 이 기능의 최대 난제가 여기 있다

## 가드가 왜 제일 중요한가

이미지 모델은 한글을 조판하는 게 아니라 **그린다.** 그래서 "맛있어" 를 "맛있ㅓ" 로
그리는 실패가 실제로 자주 난다 — 자음이나 모음이 홀로 떨어진 모양이다. 한 글자만
깨져도 카드 전체가 못 쓰게 된다.

막는 방법이 둘이다. 하나는 **온전한 음절 블록으로만 그리라**고 못 박는 것, 다른 하나는
**자신 없으면 그 메모를 통째로 빼라**고 허락하는 것이다. 두 번째가 중요하다 —
반쪽짜리 한글을 억지로 그리는 것보다 메모 하나 적은 편이 낫다.
"""

from .types import CardText, PhotoKind, WritingStyle

# ---------------------------------------------------------------------------
# 공통 스타일
# ---------------------------------------------------------------------------

_STYLE_BASE = """이 사진 위에 손글씨 메모를 얹어 여행 일기 카드로 만들어줘.

[그림체]
- 얇은 흰색 펜으로 직접 쓴 듯한 손글씨. 자연스럽고 살짝 삐뚤삐뚤하게.
- 주요 오브젝트의 외곽선을 따라 얇은 흰색 테두리를 둘러줘.
- 화살표나 부드러운 곡선 점선으로 시선을 각 아이템으로 유도해줘.
- 사진의 여백을 찾아 메모를 배치해줘. 빈 곳에 고르게 나눠 놓아줘.

[글씨 두 종류로 구분]
- 제목 1개는 크고 굵게. {title_pen}
- 나머지 메모는 전부 얇은 흰색 펜으로 작게. 제목보다 확실히 가늘게.
  굵은 글씨로 메모를 여러 개 달면 사진이 안 보인다.

[장식]
{decorations}
과하지 않게, 메모 사이사이에만 배치해줘."""

_TITLE_PEN = {
    WritingStyle.JEJU_DIALECT: (
        "굵은 붓펜이나 매직으로 힘주어 눌러쓴 듯한 한글 캘리그래피. "
        "획 두께가 들쭉날쭉하고 끝이 각지게."
    ),
    WritingStyle.DOG_DIARY: (
        "동글동글하고 통통한 손글씨. 획 두께가 일정하고 끝이 둥글게, "
        "아이가 쓴 듯 삐뚤빼뚤하게."
    ),
}

_DECORATIONS = {
    WritingStyle.JEJU_DIALECT: (
        "작은 하트(♡), 반짝이(✨), 파도 물결선, 감귤 모양을 아주 작게."
    ),
    WritingStyle.DOG_DIARY: (
        "발바닥 자국, 뼈다귀, 작은 하트(♡), 반짝이(✨), 별(★), "
        "신나서 튀는 짧은 선을 아주 작게."
    ),
}

# ---------------------------------------------------------------------------
# 분류별 내용
# ---------------------------------------------------------------------------

_KIND_HINTS = {
    PhotoKind.PET_SOLO: (
        "반려동물이 주인공이다. 표정과 자세를 가리키는 메모를 가장 눈에 띄게 배치해줘."
    ),
    PhotoKind.PET_WITH_HUMAN: (
        "반려동물과 사람이 함께 있다. 메모는 반려동물 쪽에 더 많이 두고, "
        "사람의 얼굴은 글씨나 장식으로 가리지 마."
    ),
    PhotoKind.PET_WITH_PET: (
        "반려동물이 여럿이다. 각각을 가리키는 메모를 하나씩 두어 구분되게 해줘."
    ),
    PhotoKind.SCENERY: (
        "풍경 사진이다. 사진에 동물이 없으면 동물을 그려 넣지 마. "
        "하늘·바다·바위처럼 넓은 면에 메모를 얹어줘."
    ),
    PhotoKind.FOOD: "음식 사진이다. 각 그릇과 접시를 가리키는 메모를 하나씩 두어줘.",
    PhotoKind.OBJECT: "사물이 주인공이다. 그 사물을 가리키는 메모를 중심에 두어줘.",
    PhotoKind.OTHER: (
        "사진에서 가장 눈에 띄는 것부터 가리키는 메모를 배치해줘."
    ),
}

# ---------------------------------------------------------------------------
# 가드 — 이 기능의 최대 난제
# ---------------------------------------------------------------------------

_GUARD = """[반드시 지킬 것]
- 아래 메모 문장을 **글자 그대로** 써줘. 바꾸거나 새로 지어내지 마.
- **번호나 불릿을 그리지 마.** "1." "2." "-" 같은 기호를 글자로 쓰면 안 된다.
  목록에 붙은 번호는 순서를 알려주려고 적은 것이지 카드에 넣을 글자가 아니다.
- 모든 한글은 온전한 음절 블록으로만 그린다.
  자음이나 모음이 단독으로 보이면 안 된다.
  ("맛있어" 를 "맛있ㅓ" 로 그리는 실패가 자주 난다. 절대 그러지 마.)
- 자신 없는 글자가 있으면 **그 메모를 통째로 빼고** 그 자리에 하트나 반짝임 같은
  마크만 그려줘. 반쪽짜리 한글을 억지로 그리는 것보다 메모 하나 적은 편이 낫다.
- 한 줄을 짧게 유지한다. 길수록 깨진다. 줄바꿈해서라도 짧게.
- **원본 사진을 다시 그리지 마.** 피사체의 형태·색·질감, 배경, 색감을 그대로 두고
  그 위에 손글씨와 선만 덧그려줘.
- 원본 사진의 비율을 유지한다. 자르거나 왜곡하지 마.
- 반려동물과 사람의 얼굴을 글씨나 장식으로 가리지 마.
- 사진에 없는 사물·동물·사람을 새로 그려 넣지 마."""


def build(
    kind: PhotoKind,
    style: WritingStyle,
    text: CardText,
    *,
    place_name: str | None = None,
    date_text: str | None = None,
) -> str:
    """이미지 편집 API 에 그대로 넘길 프롬프트 한 덩어리."""
    style_block = _STYLE_BASE.format(
        title_pen=_TITLE_PEN[style],
        decorations=_DECORATIONS[style],
    )

    header_lines = []
    if place_name:
        header_lines.append(f"- 장소: {place_name}")
    if date_text:
        header_lines.append(f"- 날짜: {date_text}")
    header = ""
    if header_lines:
        header = "\n\n[상단 여백에 작은 손글씨로]\n" + "\n".join(header_lines)

    # 번호를 붙이지 않는다. 붙이면 모델이 그 번호까지 글자로 그린다(실측).
    memo_block = "\n".join(f"  · {m}" for m in text.memos)

    return (
        f"{style_block}\n\n"
        f"[이 사진에 대해]\n{_KIND_HINTS[kind]}"
        f"{header}\n\n"
        f"[제목 — 크고 굵게 한 번만]\n  {text.title}\n\n"
        f"[메모 — 작고 얇게, 사진의 빈 곳에 나눠서]\n{memo_block}\n\n"
        f"{_GUARD}"
    )
