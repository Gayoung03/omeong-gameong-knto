#: 메모 뒤 괄호 표기를 쓰는 모드에서만 붙인다. 없는 표기를 설명하면 모델이 헷갈린다.
_PAREN_NOTE = """
  **괄호 안의 `(가리킬 것: ...)` `(화살표 없음)` 은 화살표 지시일 뿐 글자가 아니다.
  카드에 그리지 마라.**"""

_GUARD_PHOTO = """- **원본 사진을 다시 그리지 마.** 피사체의 형태·색·질감, 배경, 색감을 그대로 두고
  그 위에 손글씨와 선만 덧그려줘.
- 사진에 없는 사물·동물·사람을 새로 그려 넣지 마."""

_GUARD_PLATE = """- **배경은 완전한 검정 한 가지 색이다.** 회색 얼룩도, 사진의 잔상도, 흐릿한 형체도
  남아 있으면 안 된다. 나무 한 그루, 풀 한 포기도 그리지 마라.
- **흰색 말고 다른 색을 쓰지 마.** 손글씨도 화살표도 장식도 전부 흰색이다.
- 손글씨를 그림자나 테두리로 감싸지 마. 흰 획만 있으면 된다."""


#: 머리가 있는 칸을 좌표로 못 박는 자리.
#:
#: **이 블록이 생긴 이유**는 프롬프트로 네 번 말해도 안 됐기 때문이다. "얼굴을
#: 가리지 마" 는 LOOSE·PLATE 도입부·사진 종류별 힌트·공통 가드 네 곳에 있었는데
#: 09-13 과 09-14 실측에서 모두 사람 머리 위에 글씨가 앉았다. 모델이 규칙을
#: 안 읽은 것이 아니라 **머리가 어느 픽셀인지 못 맞춘 것**이다.
#:
#: 그래서 `vision` 이 같은 호출에서 칸 이름을 같이 돌려주고(비용 0), 여기서
#: 그 칸을 이름으로 박는다. 이 프로젝트에서 통한 방식은 늘 이 모양이었다 —
#: 무게 판정을 파이썬으로 옮긴 것, 메모의 화살표 대상을 우리가 정한 것.
_NO_GO = """

[비워둘 자리 — 여기엔 아무것도 그리지 마]
아래 칸에 사람이나 동물의 **머리**가 있다. 글씨·화살표·장식을 이 칸에 놓지 마라.
화면을 가로 3등분(왼쪽·가운데·오른쪽)·세로 3등분(위·중간·아래)한 칸 이름이다.
{zones}
**머리만 피하면 된다.** 몸통·다리·배경 위에는 글씨가 얹혀도 괜찮다.
뒷모습이어도 머리는 머리다."""


def build(
    kind: PhotoKind,
    style: WritingStyle,
    text: CardText,
    *,
    place_name: str | None = None,
    date_text: str | None = None,
    ink_plate: bool = False,
    loose: bool = False,
    head_zones: Sequence[str] = (),
) -> str:
    """이미지 편집 API 에 그대로 넘길 프롬프트 한 덩어리.

    `ink_plate` 가 참이면 사진이 아니라 **검은 바탕의 손글씨 레이어**를 요구한다.
    `loose` 가 참이면 배치·화살표 지시를 09-10 의 짧은 세 줄로 되돌린다
    (`_LAYOUT_LOOSE` 의 설명 참고).
    `head_zones` 는 `vision` 이 찾은 머리 칸이다. 비면 블록 자체가 빠진다 —
    가릴 머리가 없는데 금지 구역을 말하면 규칙만 하나 늘어난다.
    """
    style_block = _STYLE_BASE.format(
        layout=_LAYOUT_LOOSE if loose else _LAYOUT_STRICT,
        opening=_OPENING_PLATE if ink_plate else _OPENING_PHOTO,
        title_pen=_TITLE_PEN[style],
        title_avoid=_TITLE_AVOID[style],
        decorations=_DECORATIONS[style],
    )

    header_lines = []
    if place_name:
        header_lines.append(f"- 장소: {place_name}")
    if date_text:
        header_lines.append(f"- 날짜: {date_text}")
    header = ""
    if header_lines:
        header = "\n\n[상단 여백에 작은 손글씨로]\n" + "\n".join(header_lines)

    # 번호를 붙이지 않는다. 붙이면 모델이 그 번호까지 글자로 그린다(실측).
    # 괄호 안은 화살표를 어디로 그을지(또는 긋지 말지)를 정해 준다.
    if loose:
        memo_block = "\n".join(f"  · {m.text}" for m in text.memos)
    else:
        memo_block = "\n".join(
            f"  · {m.text}"
            + (f"   (가리킬 것: {m.target})" if m.target else "   (화살표 없음)")
            for m in text.memos
        )
    guard = _GUARD.format(
        memo_count=len(text.memos),
        paren_note="" if loose else _PAREN_NOTE,
        tail=_GUARD_PLATE if ink_plate else _GUARD_PHOTO,
    )

    no_go = ""
    if head_zones:
        no_go = _NO_GO.format(zones="\n".join(f"  · {z}" for z in head_zones))

    return (
        f"{style_block}\n\n"
        f"[이 사진에 대해]\n{_KIND_HINTS[kind]}"
        f"{no_go}"
        f"{header}\n\n"
        f"[제목 — 크고 굵게 한 번만]\n  {text.title}\n\n"
        f"[메모 — 작고 얇게, 사진의 빈 곳에 나눠서]\n{memo_block}\n\n"
        f"{guard}"
    )
